"""
STEP 4 - PUBLISH
Package the clean data for the website and for Excel / Power BI users.

  4.1  site/data/wheat.json   compact file the dashboard reads (arrays aligned to years)
  4.2  data/clean/wheat_data.xlsx   one workbook: README, stocks, wide table, production,
                                    forecasts, accuracy - for anyone who prefers Excel

Run:  python pipeline/publish.py
"""
from __future__ import annotations

import datetime as dt
import json
import sys

import pandas as pd

import config


def _num(v, decimals=0):
    if pd.isna(v):
        return None
    return round(float(v), decimals) if decimals else int(round(float(v)))


def build_json(stocks, prod, fc, acc) -> dict:
    years = list(range(int(stocks.year.min()), int(max(stocks.year.max(), prod.year.max())) + 1))
    yi = {y: i for i, y in enumerate(years)}

    geo = (pd.concat([stocks[["state", "state_abbr", "geo_level"]],
                      prod[["state", "state_abbr", "geo_level"]]])
             .drop_duplicates("state_abbr").sort_values(["geo_level", "state"]))
    states = [{"abbr": r.state_abbr, "name": r.state} for r in geo.itertuples()
              if r.state_abbr != "OTH"]

    # stocks[abbr][position][month] = [value per year]   (null = not published / withheld)
    s_out, s_flags = {}, {}
    s = stocks[stocks.wheat_class == "All Wheat"]
    for (abbr, pos, month), d in s.groupby(["state_abbr", "position", "month"]):
        arr = [None] * len(years)
        wh = [0] * len(years)
        for r in d.itertuples():
            arr[yi[r.year]] = _num(r.bushels)
            wh[yi[r.year]] = int(r.status == "withheld")
        s_out.setdefault(abbr, {}).setdefault(pos, {})[str(month)] = arr
        if any(wh):
            s_flags.setdefault(abbr, {}).setdefault(pos, {})[str(month)] = wh

    p_out = {}
    for (abbr, measure), d in prod[prod.wheat_class == "All Wheat"].groupby(["state_abbr", "measure"]):
        arr = [None] * len(years)
        for r in d.itertuples():
            arr[yi[r.year]] = _num(r.value, 1 if measure == "yield" else 0)
        p_out.setdefault(abbr, {})[measure] = arr

    # forecasts keyed like "KS|stocks|Total|12" or "KS|production"
    f_out = {}
    acc_idx = {}
    for r in acc.itertuples():
        k = (f"{r.state_abbr}|stocks|{r.position}|{int(r.month)}" if r.dataset == "stocks"
             else f"{r.state_abbr}|{r.measure}")
        acc_idx[k] = {"model": r.model_label, "mape": None if pd.isna(r.backtest_mape_pct)
                      else float(r.backtest_mape_pct)}
    for r in fc.itertuples():
        k = (f"{r.state_abbr}|stocks|{r.position}|{int(r.month)}" if r.dataset == "stocks"
             else f"{r.state_abbr}|{r.measure}")
        dec = 1 if r.measure == "yield" else 0
        e = f_out.setdefault(k, {**acc_idx.get(k, {}), "points": []})
        e["points"].append([int(r.year), _num(r.forecast, dec), _num(r.lo80, dec), _num(r.hi80, dec)])

    us = stocks[(stocks.state_abbr == "US") & (stocks.position == "Total")
                & (stocks.wheat_class == "All Wheat")]
    return {
        "meta": {
            "commodity": config.COMMODITY.title(),
            "generated": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
            "latest_stocks_date": us.date.max(),
            "latest_production_year": int(prod[prod.state_abbr == "US"].year.max()),
            "source": "USDA NASS Quick Stats (Grain Stocks; Crop Production / Small Grains Summary)",
            "source_url": "https://quickstats.nass.usda.gov/",
        },
        "years": years,
        "states": states,
        "stocks": s_out,
        "stocks_withheld": s_flags,
        "production": p_out,
        "forecasts": f_out,
    }


def build_excel(stocks, prod, fc, acc, path):
    wide = (stocks[(stocks.wheat_class == "All Wheat")]
            .assign(col=lambda d: d.date.str[:7] + " " + d.position)
            .pivot_table(index="state", columns="col", values="bushels", aggfunc="first"))
    wide = wide[sorted(wide.columns)]
    readme = pd.DataFrame({"Haystack Data Solutions - Wheat data": [
        f"Generated {dt.datetime.now():%Y-%m-%d %H:%M} from USDA NASS Quick Stats.",
        "Stocks: quarterly Grain Stocks report (Mar 1, Jun 1, Sep 1, Dec 1), bushels.",
        "Production: annual production (bu), yield (bu/acre), planted & harvested acres.",
        "Blank value + status 'withheld' = USDA (D): withheld to protect individual operations.",
        "Forecasts: statistical projections from history only - see docs/03_FORECASTING.md.",
        "Do not edit this file by hand; rerun the pipeline (run_pipeline.bat) instead.",
    ]})
    with pd.ExcelWriter(path, engine="openpyxl") as xw:
        readme.to_excel(xw, sheet_name="README", index=False)
        stocks.to_excel(xw, sheet_name="Stocks (long)", index=False)
        wide.to_excel(xw, sheet_name="Stocks (wide)")
        prod.to_excel(xw, sheet_name="Production (long)", index=False)
        fc.to_excel(xw, sheet_name="Forecasts", index=False)
        acc.to_excel(xw, sheet_name="Forecast accuracy", index=False)
        for ws in xw.book.worksheets:
            ws.freeze_panes = "B2"
            for col in ws.columns:
                width = max(len(str(c.value or "")) for c in list(col)[:200])
                ws.column_dimensions[col[0].column_letter].width = min(max(width + 2, 9), 60)


def main() -> int:
    print("[publish]")
    stocks = pd.read_csv(config.CLEAN_DIR / "wheat_stocks.csv")
    prod = pd.read_csv(config.CLEAN_DIR / "wheat_production.csv")
    fc = pd.read_csv(config.CLEAN_DIR / "wheat_forecasts.csv")
    acc = pd.read_csv(config.CLEAN_DIR / "forecast_accuracy.csv")

    data = build_json(stocks, prod, fc, acc)
    out = config.SITE_DATA_DIR / "wheat.json"
    out.write_text(json.dumps(data, separators=(",", ":")), encoding="utf-8")
    print(f"   {out.relative_to(config.ROOT)}  ({out.stat().st_size / 1024:,.0f} KB)")

    xl = config.CLEAN_DIR / "wheat_data.xlsx"
    build_excel(stocks, prod, fc, acc, xl)
    print(f"   {xl.relative_to(config.ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
